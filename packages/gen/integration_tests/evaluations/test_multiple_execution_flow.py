class TestMultipleExecutionFlow(EvaluationClientTestBase):
    """Test multiple evaluation execution flow."""

    @classmethod
    def setUpClass(cls):
        """Set up class-level resources: orchestration registry and custom metric."""
        super().setUpClass()
        
        # Initialize IDs to None in case creation fails
        cls.orchestration_registry_id = None
        cls.custom_metric_id = None
        cls.prompt_template_id = None
        try:
            # Get authentication token
            token = get_auth_token(cls.auth_url, cls.client_id, cls.client_secret)
            cls._headers = {
                'Authorization': f'Bearer {token}',
                'Content-Type': 'application/json',
            }
            
            # Model to use for orchestration registry and custom metric
            model_name = "gpt-4o"
            model_version = "latest"
            
            # Create orchestration registry configuration
            cls.orchestration_registry_id = create_orchestration_registry_config(
                cls.base_url, cls._headers, model_name, model_version
            )

            # Create prompt template
            cls.prompt_template_id = create_prompt_template(
                cls.base_url, cls._headers
            )
            
            # Create custom metric
            cls.custom_metric_id = create_custom_metric(
                cls.base_url, cls._headers, model_name, model_version
            )
        except Exception as e:
            print(f"Warning: Error during setUpClass: {e}")
            # IDs remain None, tearDownClass will handle cleanup if needed

    @classmethod
    def tearDownClass(cls):
        """Clean up class-level resources: delete orchestration registry and custom metric."""
        # Refresh token for cleanup in case it expired
        try:
            token = get_auth_token(cls.auth_url, cls.client_id, cls.client_secret)
            headers = {
                'Authorization': f'Bearer {token}',
                'Content-Type': 'application/json',
            }
        except Exception as e:
            print(f"Warning: Could not get token for cleanup: {e}")
            headers = getattr(cls, '_headers', None)
            if not headers:
                print("Warning: No headers available for cleanup")
                return
        
        # Delete orchestration registry configuration
        if hasattr(cls, 'orchestration_registry_id') and cls.orchestration_registry_id:
            delete_orchestration_registry_config(
                cls.base_url, headers, cls.orchestration_registry_id
            )

        # Delete prompt template
        if hasattr(cls, 'prompt_template_id') and cls.prompt_template_id:
            delete_prompt_template(
                cls.base_url, headers, cls.prompt_template_id
            )
        
        # Delete custom metric
        if hasattr(cls, 'custom_metric_id') and cls.custom_metric_id:
            delete_custom_metric(
                cls.base_url, headers, cls.custom_metric_id
            )
        
        super().tearDownClass()

    def test_evaluate_with_prompt_template_and_orchestration_registry(self):
        """Test evaluation with multiple configs: one with prompt template, one with orchestration registry reference and custom metric."""
        evaluation_configs = [
            # First config: Using prompt template
            EvaluationConfig(
                llm=LLM(name="gpt-4o", version="latest"),
                template=TemplateRef(template_ref=TemplateRefByID(id=self.prompt_template_id)),
                template_variable_mapping={"question": "topic"},
                dataset_config=Dataset(self.dataset_path),
                metrics=[
                    MetricConfig(
                        reference=MetricRef(id="3ea07c1f-5b10-4b12-bf46-6d429faf8010"),
                        variable_mapping={"reference": "ground_truth"},
                    ),
                ],
            ),
            # Second config: Using orchestration registry reference with custom metric
            EvaluationConfig(
                orchestration_registry_reference=self.orchestration_registry_id,
                template_variable_mapping={"question": "topic"},
                dataset_config=Dataset(self.dataset_path),
                metrics=[
                    MetricConfig(
                        reference=MetricRef(id=self.custom_metric_id),
                        # variable_mapping={
                        #     "reference": "ground_truth",
                        # },
                    ),
                ],
            ),
        ]

        evaluation_runs = self.client.evaluate(evaluation_configs)
        
        self.assertIsNotNone(evaluation_runs)
        self.assertEqual(len(evaluation_runs), 2)
        
        # Wait for all runs to complete and verify results
        for i, run in enumerate(evaluation_runs):
            run.wait_for_completion()
            results = run.results()
            metrics = results.metrics()
            
            expected_columns = {
                "submission_id",
                "run_id",
                "repetition_count",
                "metric",
                "aggregating_value",
                "metric_result",
                "error",
            }

            self.assertTrue(
                expected_columns.issubset(metrics.columns),
                f"Run {i+1}: Missing columns: {expected_columns - set(metrics.columns)}"
            )
            self.assertTrue(
                metrics["error"].isna().all(),
                f"Run {i+1}: Some metric rows contain errors:\n{metrics[metrics['error'].notna()]}"
            )


if __name__ == '__main__':
    unittest.main()
