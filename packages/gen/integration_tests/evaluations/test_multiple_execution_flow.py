def delete_orchestration_registry_config(base_url, headers, config_id):
    """Delete orchestration registry configuration."""
    if not config_id:
        return
    try:
        api_url = f"{base_url}/registry/v2/orchestrationConfigs/{config_id}"
        response = requests.delete(api_url, headers=headers)
        if response.status_code < 300:
            print(f"Orchestration registry configuration deleted: {config_id}")
        else:
            print(f"Warning: Failed to delete orchestration registry {config_id}: {response.status_code} - {response.text}")
    except Exception as e:
        print(f"Warning: Error deleting orchestration registry {config_id}: {e}")

